/// <reference types="bun" />
// Generates src/service/docs.ts from the WGSL specification.
// Usage: bun scripts/docs.ts [spec-url]; defaults to the published specification.

const url = process.argv[2] ?? "https://www.w3.org/TR/WGSL/";
const output = new URL("../src/service/docs.ts", import.meta.url);
const html = await (await fetch(url)).text();
const revision = /<meta content="([0-9a-f]+)" name="revision">/.exec(html)?.[1] ?? "unknown";

const builtinFunctionsLevel = "17.";
const constructorsLevel = "17.1.";

const typeDefinitions: Record<string, string> = {
    bool: "bool",
    i32: "i32",
    u32: "u32",
    f32: "f32",
    f16: "f16",
    vec: "vector",
    mat: "matrix",
    atomic: "atomic-type",
    array: "array",
    buffer: "buffer",
    ptr: "pointer-type",
    sampler: "sampler",
    sampler_comparison: "sampler",
    address_space: "address-spaces",
    access: "access-mode",
    texel_format: "texel-format",
};

const typeSections: Record<string, string> = {
    texture: "sampled-texture-type",
    texture_multisampled: "multisampled-texture-type",
    texture_external: "external-texture-type",
    texture_storage: "texture-storage",
    texture_depth: "texture-depth",
};

const isType = /^(?:bool|[iuf]32|f16|vec[N234]<|ptr<|atomic<|[A-Z]\w*$)/;

type Doc = [description: string, anchor: string, parameterTypes?: RegExp];

const functions = new Map<string, Doc[]>();
const attributes = new Map<string, Doc>();
const values = new Map<string, Doc>();
const types = new Map<string, Doc>();

for (const { level, anchor, title, body } of sections()) {
    const name = /^([A-Za-z_]\w*)(?: \(.+\))?$/.exec(title)?.[1];
    if (!name || !level.startsWith(builtinFunctionsLevel) || level.startsWith(constructorsLevel))
        continue;
    const docs = functions.get(name) ?? [];
    for (const [description, parameterTypes] of overloads(body))
        docs.push([description, anchor, new RegExp(`^(?:${[...parameterTypes].join("|")})$`)]);
    if (docs.length > 0) functions.set(name, docs);
}
for (const docs of functions.values()) if (docs.length === 1) docs[0]!.length = 2;

for (const { anchor, title, body } of sections())
    if (anchor.endsWith("-attr") && /^[a-z_]+$/.test(title)) {
        const description = describe(body);
        if (description) attributes.set(title, [description, anchor]);
    }

for (const table of html.matchAll(/<table class="data">([\s\S]*?)<\/table>/g)) {
    const name = cell(table[1]!, "Name");
    const description = cell(table[1]!, "Description");
    if (!name || !description || !/^[a-z_]+$/.test(text(name))) continue;
    const stage = text(cell(table[1]!, "Stage") ?? "");
    const direction = text(cell(table[1]!, "Direction") ?? "").toLowerCase();
    const line = `${stage[0]!.toUpperCase()}${stage.slice(1)} ${direction}: ${sentence(description)}`;
    const existing = values.get(text(name));
    if (existing) existing[0] += `\n\n${line}`;
    else values.set(text(name), [line, `built-in-values-${text(name)}`]);
}

const bySection = new Map([...sections()].map(section => [section.anchor, section.body]));
for (const [key, anchor] of Object.entries(typeDefinitions)) {
    const description = definition(anchor);
    if (!description) throw new Error(`definition of '${key}' not found`);
    types.set(key, [description, anchor]);
}
for (const [key, anchor] of Object.entries(typeSections)) {
    const description = describe(bySection.get(anchor) ?? "");
    if (!description) throw new Error(`section of '${key}' not found`);
    types.set(key, [description, anchor]);
}

const literal = (value: unknown): string =>
    Array.isArray(value)
        ? `[${value.map(literal).join(", ")}]`
        : value instanceof RegExp
          ? String(value)
          : JSON.stringify(value);

const write = (name: string, docs: Map<string, unknown>, type: string, comment: string): string => {
    const entries = [...docs]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([key, doc]) => `    ${JSON.stringify(key)}: ${literal(doc)},`);
    return `/** ${comment} */\nexport const ${name}: Readonly<Record<string, ${type}>> = {\n${entries.join("\n")}\n};\n`;
};

await Bun.write(
    output,
    `// Generated by scripts/docs.ts from the WGSL specification; do not edit.
// Excerpts of the WebGPU Shading Language specification, Copyright © W3C®,
// published under the W3C Software and Document License: https://www.w3.org/copyright/software-license/

/** A description and the anchor of its section in the specification. */
export type Doc = readonly [description: string, anchor: string, parameterTypes?: RegExp];

export const specification = ${JSON.stringify(url)};
export const revision = ${JSON.stringify(revision)};

${write("functions", functions, "readonly Doc[]", "Descriptions of the builtin function overloads.")}
${write("attributes", attributes, "Doc", "Descriptions of the attributes.")}
${write("values", values, "Doc", "Descriptions of the builtin values, by stage and direction.")}
${write("types", types, "Doc", "Descriptions of the predeclared types, type generators and enums.")}`,
);
console.log(
    `functions ${functions.size}, attributes ${attributes.size}, values ${values.size}, types ${types.size}`,
);

function* sections(): Generator<{ level: string; anchor: string; title: string; body: string }> {
    const headings = [
        ...html.matchAll(
            /<h[2-6][^>]* data-level="([^"]*)" id="([^"]+)"><span class="secno">[^<]*<\/span><span class="content">([\s\S]*?)<\/span>/g,
        ),
    ];
    for (let i = 0; i < headings.length; i++) {
        const heading = headings[i]!;
        const end = headings[i + 1]?.index ?? html.length;
        const body = html.slice(heading.index + heading[0].length, end);
        const title = text(heading[3]!).replaceAll("`", "");
        yield { level: heading[1]!, anchor: heading[2]!, title, body };
    }
}

/** Returns the overload descriptions of the builtin function section with their parameter types. */
function overloads(body: string): Map<string, Set<string>> {
    const found = new Map<string, Set<string>>();
    const introduction = /<p[^>]*>([\s\S]*?)<\/p>/.exec(prose(body.split("<table", 1)[0]!));
    if (introduction) return found.set(sentence(introduction[1]!), new Set());
    for (const [table] of body.matchAll(/<table class="builtin data">[\s\S]*?<\/table>/g)) {
        const description = cell(prose(table), "Description");
        if (!description) continue;
        const key = sentence(description);
        const parameterTypes = found.get(key) ?? new Set();
        for (const pattern of parameterTypePatterns(table)) parameterTypes.add(pattern);
        found.set(key, parameterTypes);
    }
    return found;
}

function describe(body: string): string | undefined {
    const text = prose(body);
    const paragraph = /<p[^>]*>([\s\S]*?)<\/p>/.exec(text);
    const table = text.indexOf("<table");
    const description =
        paragraph && (table < 0 || paragraph.index < table)
            ? paragraph[1]
            : (cell(text, "Description") ?? paragraph?.[1]);
    return description && sentence(description);
}

/** Removes the grammar, the code and the notes from the HTML. */
function prose(html: string): string {
    return html.replace(
        /<div class="syntax">[\s\S]*?<\/div>|<pre[\s\S]*?<\/pre>|<p class="note"[\s\S]*?<\/p>/g,
        "",
    );
}

/** Returns the regex patterns of the parameter types, as printed, of the table's overloads. */
function parameterTypePatterns(table: string): string[] {
    const overload = text(cell(table, "Overload") ?? "").replace(/ ?([<>]) ?/g, "$1");
    const parameters = (/\(([^()]*)\)/.exec(overload)?.[1] ?? "").replace(/\w+: /g, "");
    const dependentFirst = (cell(table, "Parameterization") ?? "")
        .split("<br>")
        .map(line => /^(\w+) is (.+?)\.?$/.exec(text(line).replaceAll("`", "")))
        .filter(match => match !== null)
        .map(([, name, union]) => {
            const options = union!.split(/,? or |, /).map(type => (isType.test(type) ? type : "*"));
            return [new RegExp(`\\b${name}\\b`, "g"), options] as const;
        })
        .reverse();
    const substitute = (list: string): string[] => {
        for (const [name, options] of dependentFirst)
            if (list.search(name) >= 0)
                return options.flatMap(type => substitute(list.replace(name, type)));
        return [list];
    };
    return substitute(parameters).map(list =>
        list
            .replace(
                /\bAbstract(Int|Float)\b/g,
                (_, kind: string) => `abstract-${kind.toLowerCase()}`,
            )
            .replace(/\b[A-Z]\w*\b|\*/g, ".+")
            .replaceAll("vecN", "vec[234]"),
    );
}

/** Returns the sentence of the definition with the anchor. */
function definition(anchor: string): string | undefined {
    const at = html.indexOf(`id="${anchor}"`);
    if (at < 0) return undefined;
    const start = Math.max(...["<p", "<td", "<li", "<dd"].map(tag => html.lastIndexOf(tag, at)));
    const ends = ["</p>", "<td", "<tr", "</li>", "</dd>", "</table>"].map(tag =>
        html.indexOf(tag, at),
    );
    const end = Math.min(...ends.filter(index => index >= 0));
    const term = text(html.slice(html.indexOf(">", at) + 1, html.indexOf("</dfn>", at)));
    const block = sentences(text(html.slice(start, end)));
    const found = block.find(sentence => sentence.includes(term)) ?? block[0];
    return found && ellipsized(found);
}

/** Returns the contents of the table cell following the cell with the label. */
function cell(table: string, label: string): string | undefined {
    const match = new RegExp(`<td[^>]*>\\s*${label}\\s*<td[^>]*>([\\s\\S]*?)(?=<tr|$)`).exec(table);
    return match?.[1];
}

/** Returns the first sentence of the HTML as text, with the flat lists inlined. */
function sentence(html: string): string {
    const inlined = html.replace(
        /<([uo]l)>((?:(?!<\/?(?:[uo]l|p|table)\b)[\s\S])*)<\/\1>/g,
        (_, _list, items: string) =>
            `${items
                .split(/<li[^>]*>/)
                .slice(1)
                .map(item => item.replace(/(?:\.|<\/li>|\s)+$/, ""))
                .join("; ")}.`,
    );
    const list = inlined.search(/<[uo]l\b/);
    const [first = "", second] = sentences(text(list < 0 ? inlined : inlined.slice(0, list)));
    return ellipsized(second && isLabel(first) ? `${first} ${second}` : first);
}

function sentences(text: string): string[] {
    return text.split(/(?<=[.!?])(?<!\b(?:e\.g|i\.e)\.)\s+(?=[A-Z`(])/);
}

function isLabel(sentence: string): boolean {
    return /^[\w-]+(?: [\w-]+){0,3}\.$/.test(sentence);
}

function ellipsized(sentence: string): string {
    return sentence.replace(/:$/, "…");
}

/** Converts the HTML to text, keeping the code in backticks. */
function text(html: string): string {
    return decode(
        html
            .replace(
                /<code[^>]*>([\s\S]*?)<\/code>/g,
                (_, code: string) => `\`${code.replace(/<[^>]+>/g, "")}\``,
            )
            .replace(/<sup>([\s\S]*?)<\/sup>/g, "^$1")
            .replace(/<[^>]+>/g, " "),
    )
        .replace(/\s+/g, " ")
        .replace(/\s+([.,;:)])/g, "$1")
        .replace(/\(\s+/g, "(")
        .trim();
}

function decode(text: string): string {
    const named: Record<string, string> = {
        lt: "<",
        gt: ">",
        amp: "&",
        quot: '"',
        apos: "'",
        nbsp: " ",
    };
    return text.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (entity, code: string) => {
        if (code.startsWith("#x")) return String.fromCodePoint(Number.parseInt(code.slice(2), 16));
        if (code.startsWith("#")) return String.fromCodePoint(Number(code.slice(1)));
        return named[code] ?? entity;
    });
}
